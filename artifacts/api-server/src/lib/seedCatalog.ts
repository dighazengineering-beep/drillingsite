export async function seedCatalogIfEmpty() {
  try {
    const p = await db.select({ id: productsTable.id }).from(productsTable).limit(1);
    if (p.length === 0) {
      await db.insert(productsTable).values(PRODUCTS as never);
      logger.info({ count: PRODUCTS.length }, "Seeded products");
    }
    const s = await db.select({ id: servicesTable.id }).from(servicesTable).limit(1);
    if (s.length === 0) {
      await db.insert(servicesTable).values(
        SERVICES.map((x) => ({ ...x, imageUrl: null, featured: false, coverageAreas: [] as string[] })) as never,
      );
      logger.info({ count: SERVICES.length }, "Seeded services");
    }
  } catch (err) {
    logger.warn({ err }, "Catalogue seeding failed");
  }
}
